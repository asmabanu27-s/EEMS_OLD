// ============================================================================
// EEMS - Application Error
// ============================================================================
//
// Central application/business error class.
//
// Use AppError for errors that are expected and should be returned to the
// client with a meaningful HTTP status code.
//
// Examples:
//   400 - Invalid request
//   404 - Resource not found
//   409 - Business conflict
//
// Unexpected errors should continue to use normal Error objects and will
// automatically become HTTP 500 responses through error-handler.ts.
// ============================================================================

export class AppError extends Error {
  /**
   * Machine-readable application error code.
   *
   * Example:
   *   LEAVE_NOT_FOUND
   *   LEAVE_OVERLAP
   *   INVALID_LEAVE_STATUS
   */
  public readonly code: string;

  /**
   * HTTP status code that should be returned to the client.
   */
  public readonly statusCode: number;

  /**
   * Indicates that this error is intentionally generated by the application
   * and is safe to expose to the API consumer.
   */
  public readonly isOperational: boolean;

  constructor(code: string, message: string, statusCode: number) {
    super(message);

    this.name = "AppError";
    this.code = code;
    this.statusCode = statusCode;
    this.isOperational = true;

    // Required for correct instanceof behavior when targeting ES5/older
    // JavaScript runtimes.
    Object.setPrototypeOf(this, new.target.prototype);
  }
}
